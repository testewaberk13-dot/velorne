export const NPCS = [];
export class Npc {
  constructor(def) {
    Object.assign(this, def); this.spr = new Sprite8(def.sheet, def.slash ? { slash: def.slash } : {});
    const p = def.start; this.x = p[0]; this.z = p[1]; this.face = 0; this.path = null; this.pi = 0; this.walkT = 0; this.entry = null; this.act = 'idle'; this.wait = 0; this.bubble = null; this.bubbleT = 0; this.talkTo = null; this.workT = 0; this.visible = true; this.speed = def.speed || 1.35;
    NPCS.push(this);
  }
  goTo(x, z) { this.path = findPath(this.x, this.z, x, z); this.pi = 1; this.dest = [x, z]; if (!this.path) { this.path = [[this.x, this.z], [x, z]]; } }
  say(t, d = 4) { this.bubble = t; this.bubbleT = d; }
}
export function currentEntry(sched, h) { let e = sched[sched.length - 1]; for (const s of sched) if (h >= s[0]) e = s; return e; }

export function updateNpcs(dt, ctx) {
  const { pois, player, onArrive, chatLines } = ctx;
  for (const n of NPCS) {
    if (n.bubbleT > 0) { n.bubbleT -= dt; if (n.bubbleT <= 0) n.bubble = null; }
    // changement de créneau horaire
    const e = currentEntry(n.sched, DAY.h); if (e !== n.entry) { n.entry = e; n.act = e[2]; n.arrived = false; n.visible = true; n.patrolI = 0; n.wanderT = 0; const tgt = targetOf(n, e, pois); if (tgt) n.goTo(tgt.x, tgt.z); }
    // conversation avec le joueur : on s'arrête et on le regarde
    if (n.talking) { n.face = Math.atan2(player.x - n.x, player.z - n.z); animate(n, dt, false); continue; }
    let moving = false;
    if (n.path && n.pi < n.path.length) {
      const [tx, tz] = n.path[n.pi]; const dx = tx - n.x, dz = tz - n.z, d = Math.hypot(dx, dz);
      // laisse passer le joueur
      const pd = Math.hypot(player.x - n.x, player.z - n.z); const blockedByPlayer = pd < 0.75 && ((player.x - n.x) * dx + (player.z - n.z) * dz) > 0;
      if (d < 0.08) n.pi++; else if (!blockedByPlayer) { const sp = Math.min(d, n.speed * dt); n.x += dx / d * sp; n.z += dz / d * sp; n.face = angLerp(n.face, Math.atan2(dx, dz), Math.min(1, dt * 10)); moving = true; }
      if (n.pi >= n.path.length) { n.path = null; n.arrived = true; onArrive && onArrive(n); }
    } else if (n.entry) {
      const p = pois[n.entry[1]];
      if (n.act === 'patrol' && n.entry[3]) { n.wait -= dt; if (n.wait <= 0) { n.patrolI = (n.patrolI + 1) % n.entry[3].length; const q = pois[n.entry[3][n.patrolI]]; if (q) n.goTo(q.x, q.z); n.wait = 3 + rnd() * 3; } }
      else if (n.act === 'wander' || n.act === 'gather') { n.wanderT -= dt; if (n.wanderT <= 0 && p) { const a = rnd() * 6.28, r = rnd() * (n.entry[3] || 3); const x = p.x + Math.cos(a) * r, z = p.z + Math.sin(a) * r; if (walkableAt(x, z)) n.goTo(x, z); n.wanderT = 4 + rnd() * 6; } }
      else if (p && p.face != null && !n.chatWith) n.face = angLerp(n.face, p.face, Math.min(1, dt * 4));
      if (n.act === 'sleep' && n.arrived) n.visible = false;
    }
    animate(n, dt, moving);
  }
  // conversations entre habitants : deux habitants arrivés à des points voisins en mode « chat »
  for (const a of NPCS) { if (a.act !== 'chat' || !a.arrived || a.talking) continue; for (const b of NPCS) { if (b === a || b.act !== 'chat' || !b.arrived || b.talking) continue; if (Math.hypot(a.x - b.x, a.z - b.z) < 4.8) { a.chatWith = b; b.chatWith = a; a.face = Math.atan2(b.x - a.x, b.z - a.z); b.face = Math.atan2(a.x - b.x, a.z - b.z); } } }
  for (const a of NPCS) { if (!a.chatWith) continue; if (a.act !== 'chat' || a.chatWith.act !== 'chat') { a.chatWith = null; continue; } a.chatT = (a.chatT || rnd() * 3) - dt; if (a.chatT <= 0 && !a.chatWith.bubble && !a.talking) { a.say(chatLines(a, a.chatWith), 3.6); a.chatT = 6 + rnd() * 4; } }
}
function targetOf(n, e, pois) { const p = pois[e[1]]; if (!p) return null; return p; }
function animate(n, dt, moving) {
  const sector = sectorOf(n.face); let sheet = 'walk', frame = 0;
  if (moving) { n.walkT += dt * 9; frame = 1 + (Math.floor(n.walkT) % 8); }
  else if (n.act === 'work' && n.arrived) { n.workT += dt; if (n.spr.sheets.slash) { sheet = 'slash'; frame = Math.floor(n.workT * 7) % n.spr.sheets.slash.cols; } else frame = (Math.floor(n.workT * 2.5) % 2) ? 0 : 2; }
  else if ((n.act === 'gather') && n.arrived) { frame = 5; }
  n.spr.set(sheet, frame, sector); const y = walkH(n.x, n.z); n.spr.place(n.x, y, n.z); n.y = y; n.spr.show(n.visible);
}
