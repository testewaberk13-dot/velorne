    if (o.tint) this.mat.color.set(o.tint);
    const W = A.w * A.s * (o.scale || 1), H = A.h * A.s * (o.scale || 1); this.mesh = new THREE.Mesh(new THREE.PlaneGeometry(W, H).translate(0, H / 2, 0), this.mat); this.mesh.castShadow = true;
    this.mesh.customDepthMaterial = new THREE.MeshDepthMaterial({ depthPacking: THREE.RGBADepthPacking, map: this.tex, alphaTest: 0.5 });
