// ---------------- planches LPC → 8 directions (même méthode que la v3) ----------------
const F = 64, SPLIT = 40, LPC = { S: 2, E: 3, N: 0, W: 1 };
function build8(img) {
  const cols = img.width / F; const c = document.createElement('canvas'); c.width = cols * F; c.height = 8 * F; const x = c.getContext('2d'); x.imageSmoothingEnabled = false;
  for (const [o, d] of [[0, 'S'], [2, 'E'], [4, 'N'], [6, 'W']]) x.drawImage(img, 0, LPC[d] * F, cols * F, F, 0, o * F, cols * F, F);
  for (const [o, t, l, s] of [[1, 'S', 'E', 1], [3, 'N', 'E', 1], [5, 'N', 'W', -1], [7, 'S', 'W', -1]]) for (let k = 0; k < cols; k++) {
    x.drawImage(img, k * F, LPC[l] * F, F, F, k * F, o * F, F, F); const W = Math.round(F * 0.86); x.clearRect(k * F, o * F, F, SPLIT - 6);
    x.drawImage(img, k * F, LPC[t] * F, F, SPLIT, k * F + (F - W) / 2 + s * 2, o * F, W, SPLIT);
  }
  const t = new THREE.CanvasTexture(c); t.magFilter = THREE.NearestFilter; t.minFilter = THREE.NearestFilter; t.generateMipmaps = false; t.colorSpace = THREE.SRGBColorSpace; t.repeat.set(1 / cols, 1 / 8); return { t, cols };
}
const loadImg = src => new Promise((r, j) => { const i = new Image(); i.onload = () => r(i); i.onerror = j; i.src = src; });
export const SHEETS = {};
export async function loadSheets(names) { await Promise.all(names.map(async n => { SHEETS[n] = build8(await loadImg('assets/demo/' + n + '.png')); })); }

// repère caméra : secteur (0 S, 1 SE, 2 E, 3 NE, 4 N, 5 NO, 6 O, 7 SO) d'un angle monde
export const CAMI = { yaw: 0 };
export function sectorOf(worldAng) { const f = [Math.sin(worldAng), Math.cos(worldAng)], r = [Math.cos(CAMI.yaw), -Math.sin(CAMI.yaw)], t = [Math.sin(CAMI.yaw), Math.cos(CAMI.yaw)]; const a = Math.atan2(f[0] * r[0] + f[1] * r[1], f[0] * t[0] + f[1] * t[1]); return ((Math.round(a / (Math.PI / 4)) % 8) + 8) % 8; }

