function buildArt(name) {
  const A = ART[name]; const rows = A.frames.map(f => f.split('\n')); const h = Math.max(...rows.map(r => r.length)), w = Math.max(...rows.map(r => Math.max(...r.map(l => l.length))));
  const c = document.createElement('canvas'); c.width = w * A.frames.length; c.height = h; const x = c.getContext('2d');
  rows.forEach((r, fi) => r.forEach((line, y) => { for (let i = 0; i < line.length; i++) { const ch = line[i]; if (ch === '.' || !A.pal[ch]) continue; x.fillStyle = A.pal[ch]; x.fillRect(fi * w + i, y + (h - r.length), 1, 1); } }));
  const t = new THREE.CanvasTexture(c); t.magFilter = t.minFilter = THREE.NearestFilter; t.generateMipmaps = false; t.colorSpace = THREE.SRGBColorSpace; t.repeat.set(1 / A.frames.length, 1);
  ANIM[name] = { t, w, h, n: A.frames.length, s: A.s, canvas: c };
}
