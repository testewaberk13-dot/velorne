const blobGeo = new THREE.CircleGeometry(0.36, 14).rotateX(-Math.PI / 2), blobMat = new THREE.MeshBasicMaterial({ color: '#000', transparent: true, opacity: 0.32, depthWrite: false });
export class Sprite8 {
  constructor(walk, extra = {}) {
    this.sheets = { walk: SHEETS[walk], ...Object.fromEntries(Object.entries(extra).map(([k, v]) => [k, SHEETS[v]])) };
    this.tex = this.sheets.walk.t.clone(); this.tex.needsUpdate = true;
    this.mat = new THREE.MeshLambertMaterial({ map: this.tex, alphaTest: 0.5, side: THREE.DoubleSide });
    this.mesh = new THREE.Mesh(new THREE.PlaneGeometry(2.0, 2.0).translate(0, 0.94, 0), this.mat); this.mesh.castShadow = true;
    this.mesh.customDepthMaterial = new THREE.MeshDepthMaterial({ depthPacking: THREE.RGBADepthPacking, map: this.tex, alphaTest: 0.5 });
    this.blob = new THREE.Mesh(blobGeo, blobMat); scene.add(this.mesh, this.blob); this.cur = 'walk';
  }
  set(sheet, frame, sector) { const s = this.sheets[sheet] || this.sheets.walk; if (s.t.image !== this.tex.image) { this.tex.image = s.t.image; this.tex.needsUpdate = true; this.tex.repeat.set(1 / s.cols, 1 / 8); this.cur = sheet; } this.tex.offset.set((frame % s.cols) / s.cols, 1 - (sector + 1) / 8); }
  place(x, y, z) { this.mesh.position.set(x, y, z); this.mesh.rotation.y = CAMI.yaw; this.blob.position.set(x, y + 0.03, z); }
  show(v) { this.mesh.visible = this.blob.visible = v; }
}

